// Bundles the fonn ui web interface (packages/cli/src/ui/web) into a
// generated TypeScript module, so the compiled CLI serves it from memory.
// The release archive only ships .js and .json files from dist/, so the
// HTML, CSS and browser scripts must travel inside a JavaScript module.
//
// Runs before the CLI package's build, typecheck and test scripts.
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'packages/cli/src/ui/web');
const output = path.join(root, 'packages/cli/src/ui/assets.generated.ts');

const TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.svg': 'image/svg+xml',
};

const files = (await readdir(source, { recursive: true }))
  .map((file) => file.split(path.sep).join('/'))
  .filter((file) => Object.hasOwn(TYPES, path.posix.extname(file)))
  .sort();

if (!files.includes('index.html')) throw new Error('packages/cli/src/ui/web/index.html is missing.');

const entries = [];
for (const file of files) {
  const body = await readFile(path.join(source, file), 'utf8');
  entries.push(`  ${JSON.stringify(`/${file}`)}: { contentType: ${JSON.stringify(TYPES[path.posix.extname(file)])}, body: ${JSON.stringify(body)} },`);
}

await writeFile(output, `// Generated by scripts/build-ui-assets.mjs from packages/cli/src/ui/web. Do not edit.
export interface UiAsset {
  contentType: string;
  body: string;
}

export const uiAssets: Readonly<Record<string, UiAsset>> = Object.freeze({
${entries.join('\n')}
});
`);
console.log(`Bundled ${files.length} fonn ui files.`);
